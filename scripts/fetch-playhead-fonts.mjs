/**
 * Fetches the PLAYHEAD type pairing and self-hosts it.
 *
 * The identity must not depend on a third-party CDN at runtime: a blocked or
 * offline fonts.googleapis.com silently degrades the whole interface to system
 * sans, which is exactly the generic look this pass removes.
 *
 * Latin + latin-ext subsets only. Two families, four weights total.
 */
import { mkdirSync, writeFileSync } from 'fs';
import { resolve } from 'path';

const OUT_DIR = resolve('public/assets/fonts');
const CSS_OUT = resolve(OUT_DIR, 'playhead-fonts.css');
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

/** Display: industrial grotesque for the mark and major titles. */
const DISPLAY = { family: 'Archivo', weights: [500, 700, 800], slug: 'archivo' };
/** System: a true workhorse terminal mono with tabular figures. */
const MONO = { family: 'IBM Plex Mono', weights: [400, 600, 700], slug: 'plexmono' };

async function fetchText(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.text();
}

async function fetchBytes(url) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return Buffer.from(await res.arrayBuffer());
}

/** Splits a Google Fonts stylesheet into @font-face blocks with their comment. */
function parseBlocks(css) {
  const blocks = [];
  const re = /\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
  let m;
  while ((m = re.exec(css)) !== null) blocks.push({ subset: m[1], body: m[2] });
  return blocks;
}

async function run() {
  mkdirSync(OUT_DIR, { recursive: true });
  const out = [
    '/* PLAYHEAD type pairing — self-hosted, latin subsets only.',
    ' * Generated by scripts/fetch-playhead-fonts.mjs. Do not hand-edit.',
    ' */',
    ''
  ];

  for (const spec of [DISPLAY, MONO]) {
    const url =
      `https://fonts.googleapis.com/css2?family=${spec.family.replace(/ /g, '+')}` +
      `:wght@${spec.weights.join(';')}&display=swap`;
    const css = await fetchText(url);
    const blocks = parseBlocks(css).filter((b) => b.subset === 'latin' || b.subset === 'latin-ext');
    console.log(`${spec.family}: ${blocks.length} subset blocks`);

    for (const block of blocks) {
      const weight = /font-weight:\s*(\d+)/.exec(block.body)?.[1] ?? '400';
      const src = /url\((https:[^)]+\.woff2)\)/.exec(block.body)?.[1];
      if (!src) continue;
      const file = `${spec.slug}-${weight}-${block.subset}.woff2`;
      writeFileSync(resolve(OUT_DIR, file), await fetchBytes(src));
      const local = block.body.replace(/url\(https:[^)]+\)/, `url('/assets/fonts/${file}')`);
      out.push(`/* ${spec.family} ${weight} ${block.subset} */`, local, '');
      console.log(`  wrote ${file}`);
    }
  }

  writeFileSync(CSS_OUT, out.join('\n'));
  console.log(`wrote ${CSS_OUT}`);
}

run().catch((err) => {
  console.error('FAILED:', err.message);
  process.exit(1);
});
